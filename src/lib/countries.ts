const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

export function findCountry(code: string): CountryEntry | undefined {
  return BY_CODE.get((code ?? "").toUpperCase());
}

/** Landnaam in de actieve UI-taal (val terug op Engels). */
export function countryName(code: string, locale: string): string {
  const entry = findCountry(code);
  if (!entry) return code;
  const key = (locale ?? "en").slice(0, 2) as "nl" | "en" | "fr" | "de";
  return entry[key] ?? entry.en;
}

/** Vlagemoji uit de landcode (regional indicator symbols). */
export function flagEmoji(code: string): string {
  const iso = (code ?? "").toUpperCase();
  if (!/^[A-Z]{2}$/.test(iso)) return "\u{1F3F3}";
  return String.fromCodePoint(...[...iso].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));
}

/** Landen gesorteerd op naam in de gevraagde taal. */
export function sortedCountries(locale: string): CountryEntry[] {
  const key = (locale ?? "en").slice(0, 2) as "nl" | "en" | "fr" | "de";
  const collator = new Intl.Collator(key);
  return [...COUNTRIES].sort((a, b) => collator.compare(a[key] ?? a.en, b[key] ?? b.en));
}
